#!/usr/bin/env python3
"""Build every Shirota style: TTF (+ ttfautohint), WOFF2 and the CSS file.

    pip install -r requirements.txt
    python build_fonts.py              # all 27 styles
    python build_fonts.py --no-hint    # skip ttfautohint
    python build_fonts.py --only Black:Expanded Regular:
"""

import argparse
import os
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from fontTools.ttLib import TTFont  # noqa: E402

from shirota.params import WEIGHTS, WIDTHS, Params  # noqa: E402
from shirota.build import build_font  # noqa: E402
from shirota.kerning import kern_feature  # noqa: E402

ROOT = os.path.dirname(HERE)


def hint(path):
    try:
        import ttfautohint
    except ImportError:
        print("  ttfautohint not installed, leaving unhinted")
        return
    tmp = path + ".tmp"
    ttfautohint.ttfautohint(in_file=path, out_file=tmp, hinting_range_min=8,
                            hinting_range_max=50, increase_x_height=0,
                            default_script="latn", fallback_script="none",
                            windows_compatibility=True)
    os.replace(tmp, path)


def woff2(path, out_dir):
    f = TTFont(path)
    f.flavor = "woff2"
    out = os.path.join(out_dir, os.path.basename(path).replace(".ttf", ".woff2"))
    f.save(out)
    return out


def css(styles, out_path):
    stretch = {"": "100%", "Wide": "125%", "Expanded": "150%"}
    lines = ["/* Shirota -- generated by source/build_fonts.py */", ""]
    for p in styles:
        fn = f"{p.ps_family}-{p.weight_name}.woff2"
        lines += [
            "@font-face {",
            f"  font-family: \"{p.family}\";",
            f"  src: url(\"../fonts/woff2/{fn}\") format(\"woff2\"),",
            f"       url(\"../fonts/ttf/{fn[:-6]}.ttf\") format(\"truetype\");",
            f"  font-weight: {p.weight_class};",
            "  font-style: normal;",
            "  font-display: swap;",
            "}",
            "",
        ]
    lines += ["/* Single-family alternative: pick the width with font-stretch. */", ""]
    for p in styles:
        fn = f"{p.ps_family}-{p.weight_name}.woff2"
        lines += [
            "@font-face {",
            "  font-family: \"Shirota Family\";",
            f"  src: url(\"../fonts/woff2/{fn}\") format(\"woff2\");",
            f"  font-weight: {p.weight_class};",
            f"  font-stretch: {stretch[p.width_suffix]};",
            "  font-style: normal;",
            "  font-display: swap;",
            "}",
            "",
        ]
    with open(out_path, "w") as fh:
        fh.write("\n".join(lines))


def charset_js(ttf, out_path):
    import json
    cps = sorted(c for c in TTFont(ttf).getBestCmap() if c > 0x20 and c != 0xA0)
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as fh:
        fh.write("window.SHIROTA_CHARSET = " + json.dumps("".join(map(chr, cps))) + ";\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-hint", action="store_true")
    ap.add_argument("--only", nargs="*", help="Weight:Width, e.g. Black:Expanded or Regular:")
    ap.add_argument("--out", default=ROOT)
    args = ap.parse_args()

    ttf_dir = os.path.join(args.out, "fonts", "ttf")
    w2_dir = os.path.join(args.out, "fonts", "woff2")
    css_dir = os.path.join(args.out, "css")
    for d in (ttf_dir, w2_dir, css_dir):
        os.makedirs(d, exist_ok=True)

    styles = [Params(w, d) for d in WIDTHS for w in WEIGHTS]
    if args.only:
        want = {tuple(s.split(":")) for s in args.only}
        styles = [p for p in styles if (p.weight_name, p.width_suffix) in want]

    for p in styles:
        path = os.path.join(ttf_dir, f"{p.ps_family}-{p.weight_name}.ttf")
        print(f"{p.family} {p.weight_name}")
        build_font(p, path, kerning=kern_feature)
        if not args.no_hint:
            hint(path)
        woff2(path, w2_dir)

    if not args.only:
        css(styles, os.path.join(css_dir, "shirota.css"))
        charset_js(os.path.join(ttf_dir, f"{styles[0].ps_family}-{styles[0].weight_name}.ttf"),
                   os.path.join(args.out, "specimen", "charset.js"))
    print("done")


if __name__ == "__main__":
    main()
